def build_day(idx):
    d = START + datetime.timedelta(days=idx)
    date_str = d.strftime("%Y.%m.%d")

    quotes = [{"text": t, "source": s, "analysis": a} for (t, s, a) in [QUOTES[(idx*3+i) % len(QUOTES)] for i in range(3)]]
    auction = [{"lot": l, "meta": m, "note": n} for (l, m, n) in [AUCTION[(idx*7+i) % len(AUCTION)] for i in range(4)]]
    ideas = [{"title": t, "cats": c, "note": n} for (t, c, n) in [IDEAS[(idx*7+i) % len(IDEAS)] for i in range(4)]]
    feature = {"kicker": FEATURE[idx % len(FEATURE)][0], "catName": FEATURE[idx % len(FEATURE)][1], "topic": FEATURE[idx % len(FEATURE)][2], "angle": FEATURE[idx % len(FEATURE)][3], "platform": FEATURE[idx % len(FEATURE)][4]}
    headlines = [HEADLINES[(idx*3+i) % len(HEADLINES)] for i in range(3)]
    copy = {"kicker": "情绪种草 · 150–200 字", "paragraph": COPY[idx % len(COPY)]}
    tags = TAGS[idx % len(TAGS)]
    strategy = [STRATEGY[idx % len(STRATEGY)]]

    ecom = [{"platform": p, "desc": ECOM[p][idx % len(ECOM[p])]} for p in ["淘宝", "抖音", "小红书", "京东", "拼多多"]]

    finance = []
    for i in range(10):
        th = FINANCE_THEMES[(idx*7 + i) % len(FINANCE_THEMES)]
        finance.append("{} · {}，{}".format(str(i+1).zfill(2), th[0] + th[1], th[2]))

    trending = []
    for i in range(10):
        ev = TRENDING_EVENTS[(idx*11 + i) % len(TRENDING_EVENTS)]
        plat = PLATS[(idx + i) % len(PLATS)]
        trending.append("{} · {} · {}".format(str(i+1).zfill(2), ev, plat))

    return {
        "date": date_str,
        "updated": "今日内容已更新",
        "quotes": quotes,
        "auction": auction,
        "finance": finance,
        "trending": trending,
        "ecom": ecom,
        "ideas": ideas,
        "feature": feature,
        "headlines": headlines,
        "copy": copy,
        "tags": tags,
        "strategy": strategy,
    }


